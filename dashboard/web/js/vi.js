const NUM = /^(\d+(?:\.\d+)*\.?\s+)(.+)$/;

/* English source text in, display text out (markdown inline syntax kept). */
export function tr(text) {
  const s = String(text == null ? "" : text).trim();
  if (Object.prototype.hasOwnProperty.call(VI, s)) return VI[s];
  const m = s.match(NUM);
  if (m && Object.prototype.hasOwnProperty.call(VI, m[2])) return m[1] + VI[m[2]];
  return text;
}
